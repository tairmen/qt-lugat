const { test } = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const { randomUUID } = require('node:crypto');

test('PostgreSQL/admin: history, review CRUD, rules, search, auth and conflicts', { skip: process.env.TEST_POSTGRES !== '1' }, async t => {
  require('dotenv').config({ path: path.join(__dirname, '..', '.env') });
  const { Pool } = require('pg');
  const express = require('express');
  const { getDatabaseConfig } = require('../database');
  const { ensureTranslationTables, createTranslationStore } = require('../translation-store');
  const { createTranslationAdmin } = require('../translation-admin');
  const { layout, escapeHtml, requireBasicAuth } = require('../admin');
  const schema = 'test_lugat_' + randomUUID().replace(/-/g,'');
  assert.match(schema, /^test_lugat_[a-f0-9]{32}$/);
  const base = new Pool({ ...getDatabaseConfig(), connectionTimeoutMillis: 5000 });
  await base.query(`CREATE SCHEMA ${schema}`);
  const pool = new Pool({ ...getDatabaseConfig(), connectionTimeoutMillis: 5000, options: `-c search_path=${schema}` });
  t.after(async () => {
    await pool.end();
    await base.query(`DROP SCHEMA ${schema} CASCADE`);
    await base.end();
  });
  await Promise.all([ensureTranslationTables(pool), ensureTranslationTables(pool)]);
  const store = createTranslationStore(pool);
  const historyId = await store.record({ chatId: 1, userId: 2, username: 'tester', text: 'Я читаю книгу. <script>alert(1)</script>', target: 'crh', result: 'Пробный ответ', model: 'test', rulesVersion: 1 });
  assert.equal(await store.report(historyId, 1, 3), false);
  assert.equal(await store.report(historyId, 1, 2), true);
  const app = express();
  app.use(express.urlencoded({ extended: false }));
  app.use(requireBasicAuth);
  app.use(createTranslationAdmin({ pool, layout, escapeHtml, adminUsername: 'editor' }));
  app.post('/words', (req,res) => res.send('legacy form works'));
  app.use((error,req,res,next) => res.status(500).send(error.message));
  const server = await new Promise(resolve => { const s = app.listen(0,'127.0.0.1', () => resolve(s)); });
  t.after(() => new Promise(resolve => server.close(resolve)));
  const root = `http://127.0.0.1:${server.address().port}`;
  const auth = 'Basic ' + Buffer.from(`${process.env.ADMIN_USERNAME || 'admin'}:${process.env.ADMIN_PASSWORD}`).toString('base64');
  const get = url => fetch(root+url, { headers: { Authorization: auth } });
  const post = (url,body) => fetch(root+url, { method:'POST', redirect:'manual', headers: { Authorization: auth, 'Content-Type':'application/x-www-form-urlencoded' }, body: new URLSearchParams(body) });
  assert.equal((await fetch(root+'/text-translations')).status,401);
  const html = await (await get('/text-translations?status=reported')).text();
  assert.ok(html.includes('&lt;script&gt;'));
  assert.ok(!html.includes('<script>alert'));
  assert.ok(html.includes('Подтверждённые переводы'));
  const detail = await (await get('/text-translations/'+historyId)).text();
  assert.ok(detail.includes('Исправить и подтвердить'));
  const form = await (await get('/confirmed-translations/new?history='+historyId)).text();
  const csrf = form.match(/name="csrf" value="([^"]+)"/)[1];
  const data = { csrf, history_id:historyId, target:'crh', source_text:'Я читаю книгу.', translated_text:'Проверенный перевод', notes:'Заметка редактора' };
  assert.equal((await post('/confirmed-translations', { ...data, csrf:'bad' })).status,403);
  assert.equal((await post('/words', {})).status,200);
  const created = await post('/confirmed-translations', data);
  assert.equal(created.status,302);
  const recordPath = created.headers.get('location').split('?')[0];
  assert.equal((await post('/confirmed-translations', data)).status,409);
  let context = await store.context({ text:'Я читаю книгу.',target:'crh' });
  assert.equal(context.examples.length,1);
  assert.equal(context.examples[0].translated_text,'Проверенный перевод');
  assert.equal((await store.context({ text:'Я читаю книгу.',target:'ru' })).examples.length,0);
  assert.equal((await store.context({ text:'😀',target:'crh' })).examples.length,0);
  assert.equal((await post(recordPath, { ...data, translated_text:'Исправленный перевод', version:'1' })).status,302);
  assert.equal((await post(recordPath, { ...data, version:'1' })).status,409);
  assert.equal((await post('/translation-rules', { csrf, version:'1', body:'Сохраняйте числа. <script>test</script>' })).status,302);
  assert.equal((await post('/translation-rules', { csrf, version:'1', body:'stale' })).status,409);
  context = await store.context({ text:'Я читаю книгу.',target:'crh' });
  assert.equal(context.version,2);
  assert.ok(context.rules.startsWith('Сохраняйте числа.'));
  assert.ok((await (await get('/translation-rules')).text()).includes('&lt;script&gt;test'));
  assert.equal((await post('/translation-rules', { csrf, version:'2', body:'' })).status,302);
  assert.equal((await store.context({ text:'Я читаю книгу.',target:'crh' })).rules,'');
  assert.equal((await post(recordPath+'/delete', { csrf, version:'2' })).status,302);
  assert.equal((await store.context({ text:'Я читаю книгу.',target:'crh' })).examples.length,0);
  assert.equal((await pool.query('SELECT id FROM text_translations WHERE id=$1',[historyId])).rowCount,1);
});
